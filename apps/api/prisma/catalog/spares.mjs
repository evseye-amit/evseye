// Insert missing entries only. Admin edits and immutable revision history survive reruns.
export async function seedSpareMasters(prisma) {
  return prisma.$transaction(async (tx) => {
    await tx.$executeRaw`SELECT pg_advisory_xact_lock(hashtext('seed:spare-masters'))`;
    const actor = await tx.user.findFirst({
      where: { clientId: null, role: 'SUPER_ADMIN', isActive: true, deletedAt: null },
      orderBy: { id: 'asc' },
    });
    if (!actor) throw new Error('Spares seed requires an active Super Admin.');
    let created = 0;
    for (const data of spareCatalog) {
      if (await tx.sparePartMaster.findUnique({ where: { code: data.code } })) continue;
      const row = await tx.sparePartMaster.create({ data: { ...data, createdById: actor.id } });
      await tx.spareCatalogueRevision.create({ data: {
        masterSpareId: row.id, version: row.version,
        snapshot: JSON.parse(JSON.stringify(row)), actorId: actor.id,
        reason: 'Initial EVSI Single Light spreadsheet seed.',
      } });
      created++;
    }
    return { created };
  });
}
