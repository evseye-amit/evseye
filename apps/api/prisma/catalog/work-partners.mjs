export async function seedWorkPartnerMasters(prisma) {
  return prisma.$transaction(async (tx) => {
    await tx.$executeRaw`SELECT pg_advisory_xact_lock(hashtext('seed:work-partner-masters'))`;
    let created = 0;
    for (const entry of workPartnerCatalog) {
      if (await tx.workPartnerMaster.findUnique({ where: { code: entry.code } })) continue;
      await tx.workPartnerMaster.create({ data: entry });
      created++;
    }
    return { created };
  });
}
