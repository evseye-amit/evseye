-- Mapping client-defined legacy labels into the closed enum vocabulary can
-- collapse previously distinct requirements to OTHER or DOCUMENT. Keep one
-- row per new key, preferring required entries and then the existing order.
WITH normalized AS (
  SELECT ctid,
    row_number() OVER (
      PARTITION BY "clientId", "workFlowType",
        CASE
          WHEN "subjectType" = 'AADHAR_PROOF_DOCUMENT' THEN 'AADHAR'
          WHEN "subjectType" = 'PAN_PROOF_DOCUMENT' THEN 'PAN'
          WHEN "subjectType" IN ('FLEET','BATTERY','CONTROLLER','IOT_DEVICE','PREPARATION','INSTALLATION','INSPECTION','PROFILE','RIDER_DOCUMENT','PAN','AADHAR','ONBOARDING_FEES','SUPPORT_TICKET','DEPLOYMENT','COLLECTION','AUTOPAY','RECEIVED') THEN "subjectType"
          WHEN "workFlowType" = 'RIDER_ONBOARDING' THEN 'RIDER_DOCUMENT'
          ELSE 'OTHER'
        END,
        CASE
          WHEN "photoType" LIKE 'RECEIPT_%' THEN 'RECEIPT'
          WHEN "photoType" LIKE 'RIDER_DOCUMENT_%' THEN 'DOCUMENT'
          WHEN "photoType" LIKE 'PDI_VOICE_%' THEN 'PDI_VOICE'
          WHEN "photoType" IN ('FRONT','BACK','LEFT','RIGHT','REAR','BODY','LABEL','CHASSIS','DASHBOARD','INSTALLATION','EVIDENCE','DOCUMENT','PROFILE','RECEIPT','RETURN_CHECKLIST','DAMAGE','DAMAGE_CLOSEUP','VEHICLE_FRONT','VEHICLE_LEFT','VEHICLE_RIGHT','VEHICLE_REAR','FLEET_FRONT','FLEET_LEFT','FLEET_RIGHT','FLEET_BACK','BATTERY_BODY','BATTERY_LABEL','CONTROLLER_BODY','CONTROLLER_LABEL','IOT_BODY','IOT_LABEL','FLEET_WITH_RIDER','RIDER_DECLARATION','PDI_VOICE','PAYMENT_RECEIPT','PENALTY_DAMAGE') THEN "photoType"
          ELSE 'OTHER'
        END
      ORDER BY "isRequired" DESC, "sortOrder" ASC, "updatedAt" DESC, "id" ASC
    ) AS duplicate_rank
  FROM "PhotoRequirement"
)
DELETE FROM "PhotoRequirement" p USING normalized n
WHERE p.ctid = n.ctid AND n.duplicate_rank > 1;

